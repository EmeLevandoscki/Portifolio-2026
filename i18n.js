function applyLang(lang) {
  localStorage.setItem('portfolio_lang', lang);
  document.documentElement.lang = lang === 'pt' ? 'pt-br' : lang;

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
    const key = el.dataset.i18nTooltip;
    if (t[key] !== undefined) el.dataset.tooltip = t[key];
  });

  document.querySelectorAll('[data-i18n-href]').forEach(el => {
    const key = el.dataset.i18nHref;
    if (t[key] !== undefined) el.href = t[key];
  });

  document.querySelectorAll('[data-i18n-download]').forEach(el => {
    const key = el.dataset.i18nDownload;
    if (t[key] !== undefined) el.download = t[key];
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('portfolio_lang') || 'pt';
  applyLang(saved);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
});
